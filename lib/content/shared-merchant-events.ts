import type {
  EventEffectTag,
  MerchantEffect,
  MerchantSituationEvent,
} from "@/lib/domain";
import { merchantAdvice, sharedMerchantEvent } from "@/lib/content/shared-event-builders";

type PaidChoice = readonly [
  label: string,
  line: string,
  resultText: string,
  effectTags: readonly EventEffectTag[],
  goldCost: number,
  merchantEffect: MerchantEffect,
];

type NeutralChoice = readonly [
  label: string,
  line: string,
  resultText: string,
  effectTags: readonly EventEffectTag[],
];

function merchantEvent(
  id: string,
  title: string,
  description: string,
  help: PaidChoice,
  harm: PaidChoice,
  neutral: NeutralChoice,
  defaultResultText: string,
): MerchantSituationEvent {
  return sharedMerchantEvent(
    id,
    title,
    description,
    [
      merchantAdvice(`${id}-a`, "help", help[0], help[1], help[2], help[3], help[4], help[5]),
      merchantAdvice(`${id}-b`, "harm", harm[0], harm[1], harm[2], harm[3], harm[4], harm[5]),
      merchantAdvice(`${id}-c`, "neutral", neutral[0], neutral[1], neutral[2], neutral[3], 0),
    ],
    defaultResultText,
  );
}

